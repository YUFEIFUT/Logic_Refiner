import type { ProviderConfig } from "./types";

/**
 * 在节点 system 指令后追加"输出格式提示"。
 *
 * 旧版（被替换）：鼓励"当你输出任何必须的数学公式，请使用标准 LaTeX 语法"。
 * 新版：默认自然语言；仅在确属可计算定量关系时才允许公式，且严禁把抽象概念塞进伪数学记号。
 */
export function enhanceSystemInstruction(system: string): string {
  return system +
    "\n输出格式提示：除非讨论的内容确实涉及可计算的定量关系（如概率、统计、度量），否则一律用自然语言表达变量关系与因果，不要使用 LaTeX 数学公式或符号代数。若确属定量场景必须使用公式，行内用单个美元符号 $...$ 书写，但严禁将非数量化的抽象概念塞进未定义、不可计算的伪数学记号中。";
}
