export function buildArchitectPrompt(input: string): string {
  return `将以下输入转化为基本的核心因果逻辑结构，识别背后的变量关系与隐含假设。

如果输入是一个问题，先给出一个你认为最合理、最有解释力的初步回答或立场，然后对该回答进行逻辑解构。
如果输入是一个观点或命题，直接进行逻辑解构。

【核心约束 - 极其重要】：
- 绝对不要使用 LaTeX 数学公式、符号代数或任何未定义、不可计算的记号（如 Y=f(...)⊗C、∑wᵢXᵢ 等）来表达逻辑。
- 变量关系、因果关系一律用自然语言的句子清楚描述。例如："当观察者的认知框架与个体特征相匹配时，更容易产生趋近行为"，而不是写成带符号的等式。
- 你可以用"因为…所以…""A 越强，B 越…"等句式表达因果与强度，不要用等号和希腊字母代替论证。
【输出要求】：最终输出必须是一个明确的、可被证伪的逻辑结构（而非一个问题分析或开放式讨论），便于后续进行压力测试。

输入： "${input}"`;
}

export function buildRedTeamPrompt(input: string, currentLogic: string): string {
  return `基于此逻辑结构：
原始观点： "${input}"
当前逻辑： ${currentLogic}

请按以下步骤进行：

第一步：理解确认
用你自己的话，简要复述当前逻辑的核心论点和关键变量关系（2-3 句话）。这一步必须用自然语言完成，不要使用公式或符号代数。
这一步的目的是确认你真正理解了对方在说什么，而不是攻击一个你误解的版本。

第二步：精准反驳
基于你的理解，列出 3-5 个有力的反例或边界情况。每个反例必须：
1. 针对当前逻辑的实际论点，而非你复述时可能引入的简化
2. 在当前逻辑的讨论层级内有效（如逻辑在讨论认知现象，就不得用量子物理等不同层级的场景来反驳）
3. 说明该反例具体击中了当前逻辑的哪个环节（前提、推理链条、隐含假设）

【格式约束 - 极其重要】：你的反驳必须用自然语言论述，不得引入或沿用 LaTeX 公式、符号代数等未定义记号。如果上游逻辑用了公式，请用你自己的话把它翻译成自然语言后再批评。`;
}

export function buildSynthesizerPrompt(input: string, currentLogic: string, redTeamOutput: string): string {
  return `原始观点： "${input}"
当前逻辑： ${currentLogic}
红方反例： ${redTeamOutput}

请按以下步骤进行：

第一步：反例质量评估
逐个审视红方的反例，判断其有效性：
- 对于成立的反例：说明它击中了当前逻辑的哪个具体弱点
- 对于不成立的反例：说明为什么不成立（如：曲解了原逻辑、范畴错位、与当前逻辑已处理的问题重复）
- 对于重复的反例（当前逻辑已覆盖或上一轮修正要点已处理）：标注为已覆盖

第二步：逻辑精炼
仅基于你判定为有效的反例，对逻辑进行"非线性"提炼。
1. 剥离表面陈词滥调和鸡汤噪音。
2. 引入更本质的隐性变量（如认知边界、情境约束、反馈回路）来融合红方的质疑。
3. 产出一个更深刻、更具包容性的逻辑关系时，绝对不要使用 LaTeX 公式或符号代数（包括但不限于 ∑、∫、⊗、自定义函数 f( )、希腊字母变量等）。用自然语言融合概念、讲清因果，而不是把关系伪装成等式。
4. 【核心约束】你产出的逻辑必须与原始观点"${input}"相关，是对该观点的深化或修正，而非脱离主题的新创造。
5. 【证伪约束】新逻辑应比当前逻辑更难找到反例。如果无法做到，需明确说明当前逻辑已是最佳状态。
6. 【简洁原则】尽可能简洁（奥卡姆剃刀原则），不要引入不必要的变量或条件，准确描述变量之间的因果关系，不多不少。`;
}

export function buildBoundaryPrompt(input: string, currentLogic: string): string {
  return `原始观点： "${input}"
最终迭代后的精炼逻辑： ${currentLogic}

1. 定义该逻辑有效的"场域"（适用空间与适用限度）。
2. 评估该逻辑在复杂系统下的稳定性和局限性。
3. 提供一个关于此真理在现实世界中成立的概率或贝叶斯认知建议。
4. 【核心约束】你的分析必须与原始观点"${input}"相关，明确说明精炼后的逻辑如何回应了原始观点。

【格式约束 - 极其重要】：你关于"场域""稳定性""贝叶斯认知建议"的表述，必须用自然语言，不得写成 P(...) 形式的概率等式或 κ→0 类的极限记号。用"在…情境下更成立 / 更脆弱"等句式表达边界与概率。`;
}

export interface CrystallizationArgs {
  architectOutput: string;
  currentLogic: string;
  boundaryOutput: string;
  input: string;
}

export function buildCrystallizationPrompt(args: CrystallizationArgs): string {
  const { architectOutput, currentLogic, boundaryOutput, input } = args;
  return `请基于以下所有分析过程，产出一个经过证伪检验的、简洁的、难以反驳的逻辑表述。

分析过程：
- 初始架构：${architectOutput}
- 最终演化逻辑：${currentLogic}
- 边界分析：${boundaryOutput}
- 原始命题： "${input}"

【核心标准 - 极其重要】：
1. 难以证伪：在目前已知的认知范围内，找不到轻易推翻它的反例
2. 奥卡姆剃刀：表述尽可能简洁，不引入不必要的变量或条件——真理往往是简单的
3. 准确描述因果关系：不多不少，恰好说清楚变量之间的本质关系
4. 与原始命题相关：必须是对原始命题"${input}"的精炼，而非脱离主题的新创造
5. 具备系统性视角：揭示命题在更大系统中的位置、边界和相互作用

【禁止事项】：
- 绝对不要产出"形而上""震撼""充满张力"等形式化表述
- 绝对不要将抽象概念强行塞进数学或物理公式

【期望结果】：
一个简洁、准确、难以反驳的逻辑表述，例如：
"努力是成功的必要非充分条件，其有效性受方向选择、环境结构和随机因素共同调节。"

仅输出这句精炼结论，绝不要带有任何前言、引言、多余说明。`;
}

export function buildExplainerPrompt(finalLogic: string): string {
  return `请对以下经过证伪检验的逻辑表述进行通俗易懂的解读：
最终结论：${finalLogic}

1. 用通俗、生动但绝不廉价的语言，解读该结论的核心含义与逻辑关系。
2. 提供 2 个生活或工作中的实际对照/应用例子，帮助用户透彻理解这一结论。

【格式约束 - 极其重要】：你的通俗解读本身就不该出现公式；若结论里出现了符号，请先把它翻译成自然语言，再给生活例子。`;
}
